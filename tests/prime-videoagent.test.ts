function fakeSource(rows = ROWS, fail: { search?: boolean; read?: boolean } = {}) {
  const reads: string[] = [], searches: string[] = [];
  return {
    reads, searches,
    async read(id: string) {
      reads.push(id); if (fail.read) throw new Error('broker down');
      const row = rows[id]; if (!row) throw new Error('Unknown capability');
      return { capability: { id, description: row.description, tier: row.tier }, registration_state: row.registered === false ? 'unregistered' : 'registered', health_status: row.health };
    },
    async search(query: string) {
      searches.push(query); if (fail.search) throw new Error('search down');
      const words = query.toLowerCase().split(/\s+/);
      return Object.entries(rows).filter(([id, r]) => words.some(w => (id + ' ' + r.description).toLowerCase().includes(w))).map(([id, r]) => ({ id, description: r.description, registered: r.registered !== false, health: r.health }));
    },
  };
}
