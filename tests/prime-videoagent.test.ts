// ---- routes against a stand-in echo-adk-api ---------------------------------------------------------------------------
type Seen = { method: string; url: string; body: unknown };
const servers: Server[] = [], closers: (() => Promise<void>)[] = [];
afterEach(async () => {
  while (closers.length) await closers.pop()!();
  while (servers.length) { const s = servers.pop()!; s.closeAllConnections(); await new Promise<void>(r => s.close(() => r())); }
});
const REGISTRY = new Set(['echo.media.video_generate', 'echo.media.job_status', 'echo.voice.speak', 'echo.elevenlabs.tts']);
async function fakeAdk(agents: Record<string, unknown>[] = []) {
  const seen: Seen[] = [];
  const server = createServer((req, res) => {
    const chunks: Buffer[] = [];
    req.on('data', c => chunks.push(c));
    req.on('end', () => {
      const raw = Buffer.concat(chunks).toString('utf8'), body = raw ? JSON.parse(raw) : undefined, path = (req.url ?? '').split('?')[0];
      seen.push({ method: req.method ?? '', url: req.url ?? '', body });
      res.setHeader('content-type', 'application/json');
      const reply = (status: number, value: unknown) => { res.statusCode = status; res.end(JSON.stringify(value)); };
      if (req.method === 'POST' && path === '/agents') {
        const origin = body.origin ?? {};
        if (Object.keys(origin).some(k => k !== 'by' && k !== 'prompt_sha256')) { reply(400, { error: 'invalid', message: 'origin accepts by and prompt_sha256 only; the service stamps created_at' }); return; }
        if (body.max_steps > 64) { reply(400, { error: 'invalid', message: 'agent.max_steps out of range' }); return; }
        const unknown = (body.capabilities as string[]).filter(c => !REGISTRY.has(c));
        if (unknown.length) { reply(400, { error: 'invalid', message: 'capabilities not in the registry (default-deny): ' + JSON.stringify(unknown) }); return; }
        if (agents.some(a => a.name === body.name)) { reply(409, { error: 'invalid', message: `agent '${body.name}' already exists` }); return; }
        const made = { ...body, origin: { ...origin, created_at: '2026-11-05T07:00:00+00:00' }, source: body.name + '.json' }; agents.push(made); reply(201, made);
      } else if (req.method === 'GET' && path.startsWith('/agents/')) {
        const a = agents.find(x => x.name === decodeURIComponent(path.slice(8))); if (a) reply(200, a); else reply(404, { error: 'not_found', message: 'no such agent' });
      } else if (req.method === 'POST' && path === '/runs') reply(202, { run_id: RUN, status: 'queued' });
      else reply(404, { error: 'not_found', message: 'not found' });
    });
  });
  await new Promise<void>(r => server.listen(0, '127.0.0.1', () => r())); servers.push(server);
  return { url: 'http://127.0.0.1:' + (server.address() as AddressInfo).port, seen, agents };
}
function broker(source = fakeSource()): SdkBroker & { source: ReturnType<typeof fakeSource> } {
  return { source, read: id => source.read(id), search: async q => (await source.search(q)).map(r => ({ id: r.id, description: r.description, registered: r.registered, health: r.health, category: 'discovered' }) as Capability), invoke: async () => { throw new Error('video planning never invokes a capability'); } };
}
async function prime(options: { adk?: string; sdk?: SdkBroker | null; uploads?: UploadStore } = {}) {
  const hub = new PrimeHub({ capabilities: [], ...(options.adk ? { adk: new AdkClient({ ...DEFAULT_ADK, baseUrl: options.adk }) } : {}), ...(options.sdk ? { sdk: options.sdk } : {}), ...(options.uploads ? { uploads: options.uploads, uploadsOwner: 'owner-1' } : {}) });
  const server = await startPrimeServer(hub, UI, 0); closers.push(server.close);
  const cookie = (await fetch(server.url)).headers.get('set-cookie')!.split(';')[0]!;
  const call = async (path: string, body?: unknown, withCookie = true) => {
    const response = await fetch(server.url + path, { method: body === undefined ? 'GET' : 'POST', headers: { ...(withCookie ? { cookie } : {}), 'x-prime-request': '1', origin: server.url, ...(body === undefined ? {} : { 'content-type': 'application/json' }) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    // eslint-disable-next-line @typescript-eslint/no-explicit-any -- route answers are untyped JSON read field by field in the assertions
    return { status: response.status, body: await response.json() as Record<string, any> };
  };
  return { url: server.url, call };
}

